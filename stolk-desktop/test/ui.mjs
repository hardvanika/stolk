// Drives the renderer in Chromium against test/mock-bridge.js. Run: node test/ui.mjs (needs Playwright installed globally).
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import { execSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const { chromium } = require(path.join(execSync('npm root -g').toString().trim(), 'playwright'));
const here = path.dirname(new URL(import.meta.url).pathname);
const out = process.argv[2] || path.join(here, 'shots');
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const errors = [];
const checks = [];
const check = (cond, msg) => { checks.push(msg); if (!cond) errors.push(`FALLA: ${msg}`); };
for (const [label, viewport] of [['desktop', { width: 1440, height: 900 }], ['panel', { width: 440, height: 900 }]]) {
  const page = await browser.newPage({ viewport });
  page.on('pageerror', (e) => errors.push(`${label}: ${e.message}`));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(`${label}: ${m.text()}`); });
  await page.addInitScript({ content: 'window.STOLK_TODAY = "2026-11-19";' });
  await page.addInitScript({ path: path.join(here, 'sample-data.js') });
  await page.addInitScript({ path: path.join(here, 'mock-bridge.js') });
  await page.clock.setFixedTime(new Date('2026-11-19T18:30:00'));
  await page.goto('file://' + path.join(here, '..', 'renderer', 'index.html'));
  await page.waitForSelector('#askInput');
  await page.fill('#askInput', '¿A quién conocí en Tech & Tapas #3?');
  await page.click('#askForm button[type=submit]');
  await page.waitForSelector('.answer');
  check((await page.textContent('.answer')).includes('Lucía'), `${label}: Preguntar muestra la respuesta del servidor`);
  check((await page.inputValue('#askInput')) === '', `${label}: la caja de Preguntar se vacía al enviar`);
  await page.fill('#askInput', 'escribe a Jorge para el deck');
  await page.click('#askForm button[type=submit]');
  await page.waitForSelector('#askDraftText');
  check((await page.inputValue('#askDraftText')).includes('deck'), `${label}: Preguntar deja el borrador editable`);
  await page.screenshot({ path: `${out}/${label}-preguntar.png` });
  for (const v of ['hoy', 'calendario', 'contactos', 'proyectos', 'eventos', 'integraciones']) {
    await page.evaluate((h) => { location.hash = h; }, v);
    await page.waitForTimeout(200);
    check(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), `${label}: ${v} sin scroll horizontal`);
    if (label === 'desktop') check(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight && document.querySelector('.topbar').getBoundingClientRect().top === 0), `desktop: ${v} no hace scroll de la ventana`);
    await page.screenshot({ path: `${out}/${label}-${v}.png` });
    if (v === 'calendario') check((await page.textContent('main')).includes('Lucía'), `${label}: Calendario se pinta con una reserva de alguien que no es contacto`);
    if (v === 'calendario' && label === 'desktop') {
      await page.click('.month .day[data-id="2026-11-21"]', { position: { x: 60, y: 90 } });
      await page.waitForSelector('.day-list');
      check((await page.textContent('.day-list')).includes('lucia@example.com'), `${label}: al pulsar un día se amplía con todo lo de ese día`);
      await page.screenshot({ path: `${out}/${label}-dia.png` });
      await page.click('[data-action="save-attendee"]');
      check((await page.inputValue('#cName')) === 'Lucía Ferrer' && (await page.inputValue('#cEmail')) === 'lucia@example.com', `${label}: Guardar persona rellena la ficha con la reserva`);
      await page.click('[data-action="close-modal"].btn');
      await page.click('.month .day[data-id="2026-11-27"]', { position: { x: 60, y: 90 } });
      await page.click('.modal [data-action="new-event"]');
      check((await page.inputValue('#eDate')) === '2026-11-27', `${label}: Nuevo evento desde el día usa esa fecha`);
      await page.click('[data-action="close-modal"].btn');
    }
  }
  await page.evaluate(() => { location.hash = 'hoy'; });
  await page.waitForTimeout(150);
  check((await page.locator('.today-row').count()) === 3, `${label}: Hoy enseña las 3 reuniones de hoy`);
  check((await page.evaluate(() => window.STOLK_BADGE)) >= 3, `${label}: el icono del dock lleva el número de cosas de hoy`);
  // Editar con Claude in a person's Conversaciones card: rewrites in place, undo restores.
  await page.evaluate(() => { location.hash = 'contactos'; });
  await page.waitForTimeout(150);
  await page.locator('[data-action="select-contact"]').first().click();
  await page.waitForSelector('#personText');
  check(!(await page.textContent('#personSend')).includes('Sin Claude'), `${label}: Conversaciones ya no dice «Sin Claude»`);
  await page.fill('#personText', 'Holi, que t');
  await page.click('[data-edit-text]');
  await page.waitForFunction(() => document.getElementById('personText').value.startsWith('Holi, ¿qué tal?'));
  check(!(await page.evaluate(() => window.STOLK_CALLS)).some((c) => /opened/.test(c)), `${label}: Editar con Claude no envía ni anota nada`);
  await page.screenshot({ path: `${out}/${label}-editar-mensaje.png` });
  await page.click('[data-undo-edit]');
  check((await page.inputValue('#personText')) === 'Holi, que t', `${label}: Deshacer recupera tu texto`);
  // People picker in Nuevo proyecto: search, add chips, remove one, submit.
  await page.evaluate(() => { location.hash = 'proyectos'; });
  await page.waitForTimeout(150);
  await page.click('[data-action="new-project"]');
  await page.fill('#pTitle', 'Hackathon');
  await page.fill('#pPeople', 'ribera');
  check((await page.locator('#pPeopleList li[data-cid]').count()) === 1, `${label}: el buscador filtra por empresa`);
  await page.keyboard.press('Enter');
  await page.fill('#pPeople', 'lucia');
  await page.click('#pPeopleList li[data-cid="1"]');
  await page.fill('#pPeople', 'marta');
  await page.keyboard.press('Enter');
  await page.click('#pPeopleChips [data-remove="3"]');
  check((await page.locator('#pPeopleChips .pick-chip').count()) === 2, `${label}: se añaden y quitan personas como chips`);
  await page.screenshot({ path: `${out}/${label}-buscador.png` });
  await page.click('#modalForm button[type=submit]');
  await page.waitForTimeout(250);
  const proj = await page.evaluate(() => window.STOLK_DATA.projects[0]);
  check(proj.title === 'Hackathon' && proj.people.map((x) => x.cid).join() === '2,1', `${label}: el proyecto se crea con las personas elegidas`);
  // Same picker for Invitados in Nuevo evento.
  await page.evaluate(() => { location.hash = 'eventos'; });
  await page.waitForTimeout(150);
  await page.click('[data-action="new-event"]');
  await page.fill('#eGuests', 'jorge');
  await page.keyboard.press('Enter');
  check((await page.locator('#eGuestsChips input[name=guests][value="2"]').count()) === 1, `${label}: Invitados usa el mismo buscador`);
  await page.keyboard.press('Escape');
  check((await page.locator('#modalForm').count()) === 1, `${label}: Escape en el buscador cierra la lista, no el modal`);
  await page.click('[data-action="close-modal"].btn');
  // Capture flow: reading -> card -> save as new contact.
  await page.evaluate(() => window.STOLK_FAKE_CAPTURE({ status: 'reading', image: '' }));
  await page.waitForSelector('text=Leyendo tu captura');
  await page.evaluate(() => window.STOLK_FAKE_CAPTURE({ status: 'ok', image: '', card: { found: true, name: 'Nora Gil', role: 'CTO', company: 'Brezo', email: 'nora@brezo.example', phone: '', linkedin: 'linkedin.com/in/noragil', website: '', notes: 'Habló en el panel de IA.' } }));
  await page.waitForSelector('#cap-name');
  await page.screenshot({ path: `${out}/${label}-captura.png` });
  await page.click('#modalForm button[type=submit]');
  await page.waitForTimeout(250);
  const calls = await page.evaluate(() => window.STOLK_CALLS);
  check(calls.includes('POST /contacts') && calls.includes('POST /interactions'), `${label}: Guardar captura crea la persona y su historial`);
  check((await page.textContent('main')).includes('Nora Gil'), `${label}: la persona capturada aparece en Personas`);
  // Capture of someone already saved -> merge (PATCH).
  await page.evaluate(() => window.STOLK_FAKE_CAPTURE({ status: 'ok', image: '', card: { found: true, name: 'Jorge Sanz', role: '', company: '', email: '', phone: '', linkedin: '', website: 'ribera.example', notes: '' } }));
  await page.waitForSelector('input[name=merge]');
  await page.click('#modalForm button[type=submit]');
  await page.waitForTimeout(250);
  check((await page.evaluate(() => window.STOLK_CALLS)).some((c) => c.startsWith('PATCH /contacts/2')), `${label}: una captura repetida se fusiona con la ficha existente`);
  // Sync at startup, chat buttons log through /contacts/:id/opened, model picker in Ajustes.
  const all = await page.evaluate(() => window.STOLK_CALLS);
  check(all.includes('POST /sync'), `${label}: sincroniza al arrancar`);
  await page.evaluate(() => { location.hash = 'integraciones'; });
  await page.waitForSelector('#claudeModel');
  await page.selectOption('#claudeModel', 'claude-haiku-5-5');
  await page.waitForTimeout(200);
  check((await page.evaluate(() => window.STOLK_CALLS)).includes('PATCH /settings'), `${label}: el modelo de Claude se cambia en Ajustes`);
  await page.click('main button[data-action=gcal-on]');
  await page.waitForTimeout(2600);
  const gcalls = await page.evaluate(() => window.STOLK_CALLS);
  check(gcalls.includes('POST /connections/gcal/start') && gcalls.includes('open https://auth.example/consent'), `${label}: Continuar con Google abre el navegador`);
  check(!(await page.locator('button[data-action=gcal-on]').count()), `${label}: Google aparece conectado al volver`);
  await page.click('button[data-action=sync]');
  await page.waitForTimeout(250);
  check((await page.evaluate(() => window.STOLK_CALLS)).filter((c) => c === 'POST /sync').length >= 2, `${label}: el botón Sincronizar llama al servidor`);
  await page.click('button[data-action=mcp-on][data-id=desktop]');
  await page.waitForSelector('button[data-action=mcp-off][data-id=desktop]');
  check((await page.evaluate(() => window.STOLK_CALLS)).includes('POST /integrations/claude/desktop'), `${label}: Ajustes conecta Stölk con Claude desktop`);
  await page.locator('button[data-action=mcp-off][data-id=desktop]').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, `${label}-ajustes-claude.png`) });
  await page.evaluate(() => { location.hash = 'contactos'; });
  await page.waitForTimeout(200);
  await page.evaluate(() => document.querySelector('#personSend a[data-sent]')?.addEventListener('click', (e) => e.preventDefault(), { once: true }));
  const chat = page.locator('#personSend a[data-sent]').first();
  if (await chat.count()) {
    check((await chat.getAttribute('href')).startsWith('https://web.whatsapp.com/send?phone='), `${label}: en Linux WhatsApp abre WhatsApp Web directo`);
    await chat.click();
    await page.waitForTimeout(250);
    await page.evaluate(() => document.querySelector('#personSend a[data-sent="Telegram"]')?.addEventListener('click', (e) => e.preventDefault(), { once: true }));
    await page.click('#personSend a[data-sent="Telegram"]');
    await page.waitForTimeout(250);
    const compact = page.locator('.timeline li.opened');
    check((await compact.count()) === 1 && (await compact.textContent()).includes('WhatsApp, Telegram'), `${label}: abrir chats sale como una sola línea corta en el Historial`);
    check((await page.evaluate(() => window.STOLK_CALLS)).some((c) => /^POST \/contacts\/\d+\/opened$/.test(c)), `${label}: abrir un chat queda en el historial`);
  } else check(false, `${label}: hay botones de chat en la ficha`);
  await page.evaluate(() => window.STOLK_FAKE_UPDATE('0.1.2'));
  await page.waitForSelector('#updateBar');
  check((await page.textContent('#updateBar')).includes('Nueva versión disponible'), `${label}: avisa de una versión nueva`);
  await page.click('#updateBar .btn.primary');
  check((await page.evaluate(() => window.STOLK_CALLS)).includes('update:install'), `${label}: Reiniciar instala la actualización`);
  await page.close();
}
await browser.close();
console.log(checks.length - errors.filter((e) => e.startsWith('FALLA')).length + '/' + checks.length + ' comprobaciones OK');
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
